"""Full-output scientific and boundary checks for the first native sequence slice.

Provenance: INSDC Feature Table 11.4 (April 2026), sections 7.4.1 and 7.4.3,
https://www.insdc.org/submitting-standards/feature-table/ . The independent
set-based oracle below does not import BioV or Biopython complement tables.
Biopython 1.88 is the separately versioned differential reference in uv.lock.
See docs/guides/sequence-contract.md for the accepted contract and limitations.
"""

import importlib
import random
from collections.abc import Callable
from importlib.machinery import EXTENSION_SUFFIXES
from itertools import product
from pathlib import Path

import Bio
import pandas as pd
import pytest
from Bio.Seq import Seq as ReferenceSeq

import biov

REFERENCE_BIOPYTHON_VERSION = "1.88"
DNA_ALPHABET = "ACGTRYSWKMBDHVN"
RNA_ALPHABET = "ACGURYSWKMBDHVN"
PROTEIN_ALPHABET = "ACDEFGHIKLMNPQRSTVWYBJOUXZ*"
OPERATIONS = ("normalize_sequences", "reverse_complements")

# Biological set meanings transcribed from INSDC 11.4 section 7.4.1.
# Sets plus canonical-base pairing provide a structurally independent oracle.
_DNA_BASE_SETS = {
    "A": frozenset("A"),
    "C": frozenset("C"),
    "G": frozenset("G"),
    "T": frozenset("T"),
    "R": frozenset("AG"),
    "Y": frozenset("CT"),
    "S": frozenset("CG"),
    "W": frozenset("AT"),
    "K": frozenset("GT"),
    "M": frozenset("AC"),
    "B": frozenset("CGT"),
    "D": frozenset("AGT"),
    "H": frozenset("ACT"),
    "V": frozenset("ACG"),
    "N": frozenset("ACGT"),
}

# Hand-derived one-symbol fixtures, not generated by the new implementation.
_DNA_SYMBOL_COMPLEMENTS = (
    ("A", "T"),
    ("C", "G"),
    ("G", "C"),
    ("T", "A"),
    ("R", "Y"),
    ("Y", "R"),
    ("S", "S"),
    ("W", "W"),
    ("K", "M"),
    ("M", "K"),
    ("B", "V"),
    ("D", "H"),
    ("H", "D"),
    ("V", "B"),
    ("N", "N"),
)


def _set_oracle(value: str, kind: str) -> str:
    """Derive each ambiguous complement from canonical nucleotide sets.

    Returns:
        Complete reverse complement encoded with the declared IUPAC alphabet.
    """
    base_sets = _DNA_BASE_SETS
    pairing = {"A": "T", "T": "A", "C": "G", "G": "C"}
    if kind == "rna":
        base_sets = {
            symbol.replace("T", "U"): frozenset(
                base.replace("T", "U") for base in bases
            )
            for symbol, bases in _DNA_BASE_SETS.items()
        }
        pairing = {"A": "U", "U": "A", "C": "G", "G": "C"}
    symbol_for_set = {bases: symbol for symbol, bases in base_sets.items()}
    return "".join(
        symbol_for_set[frozenset(pairing[base] for base in base_sets[symbol])]
        for symbol in reversed(value.upper())
    )


def _deterministic_corpus(kind: str) -> list[str | None]:
    """Return all words through length three and seeded longer mixed-case rows."""
    alphabet = DNA_ALPHABET if kind == "dna" else RNA_ALPHABET
    values: list[str | None] = [
        "".join(symbols)
        for length in range(4)
        for symbols in product(alphabet, repeat=length)
    ]
    rng = random.Random(20261003)  # noqa: S311 - reproducible scientific fixture
    for length in [0, 1, 2, 3, 4, 15, 16, 31, 32, 63, 64, 255, 256, 4096]:
        for _ in range(8):
            sequence = "".join(rng.choice(alphabet) for _ in range(length))
            values.append(
                "".join(
                    symbol.lower() if rng.randrange(2) else symbol
                    for symbol in sequence
                )
            )
    values[1:1] = [None, "", alphabet.lower(), None, alphabet.lower()]
    return values


def test_native_module_is_a_compiled_extension() -> None:
    """Reject a Python fallback masquerading as the native implementation."""
    native = importlib.import_module("biov._native")
    origin = native.__file__
    assert origin is not None
    assert any(origin.endswith(suffix) for suffix in EXTENSION_SUFFIXES), origin
    assert Path(origin).parent == Path(biov.__file__).parent
    assert callable(native.normalize_sequences)
    assert callable(native.reverse_complements)


def test_validation_exception_is_shared_and_value_error() -> None:
    """Expose one public validation exception across both Python surfaces."""
    from biov.seq import SequenceValidationError

    assert biov.SequenceValidationError is SequenceValidationError
    assert issubclass(biov.SequenceValidationError, ValueError)


@pytest.mark.parametrize(
    ("kind", "alphabet"),
    [("dna", DNA_ALPHABET), ("rna", RNA_ALPHABET), ("protein", PROTEIN_ALPHABET)],
)
def test_complete_alphabets_normalize_without_losing_rows(
    kind: str, alphabet: str
) -> None:
    """Retain order, duplicates, empty strings and explicit nulls."""
    values = [alphabet.lower(), None, "", alphabet, alphabet.lower(), None]
    before = values.copy()
    result = biov.normalize_sequences(values, kind=kind)

    assert result == [alphabet, None, "", alphabet, alphabet, None]
    assert isinstance(result, list)
    assert result is not values
    assert values == before
    result[0] = ""
    assert values == before


@pytest.mark.parametrize(("symbol", "complement"), _DNA_SYMBOL_COMPLEMENTS)
@pytest.mark.parametrize("kind", ["dna", "rna"])
def test_every_iupac_symbol_has_its_hand_checked_complement(
    symbol: str, complement: str, kind: str
) -> None:
    """Check every ambiguity code individually, including lowercase inputs."""
    if kind == "rna":
        symbol = symbol.replace("T", "U")
        complement = complement.replace("T", "U")
    assert biov.reverse_complements([symbol, symbol.lower()], kind=kind) == [
        complement,
        complement,
    ]


