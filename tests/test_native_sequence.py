@pytest.mark.parametrize("kind", ["dna", "rna"])
def test_full_corpus_agrees_with_independent_set_oracle(kind: str) -> None:
    """Compare every result with a set-based derivation of IUPAC complement."""
    values = _deterministic_corpus(kind)
    expected = [None if value is None else _set_oracle(value, kind) for value in values]
    assert biov.reverse_complements(values, kind=kind) == expected


@pytest.mark.parametrize("kind", ["dna", "rna"])
def test_full_corpus_agrees_with_versioned_biopython(
    kind: str, record_property: Callable[[str, object], None]
) -> None:
    """Run the separately implemented, pinned scientific differential reference."""
    record_property("biopython_reference_version", Bio.__version__)
    assert Bio.__version__ == REFERENCE_BIOPYTHON_VERSION, (
        "The scientific reference changed: install Biopython "
        f"{REFERENCE_BIOPYTHON_VERSION} from uv.lock, or explicitly review and "
        "update the reference version and sequence-contract provenance."
    )
    values = _deterministic_corpus(kind)
    expected = [
        None
        if value is None
        else str(
            ReferenceSeq(value.upper()).reverse_complement()
            if kind == "dna"
            else ReferenceSeq(value.upper()).reverse_complement_rna()
        )
        for value in values
    ]
    assert biov.reverse_complements(values, kind=kind) == expected


@pytest.mark.parametrize("kind", ["dna", "rna"])
def test_involution_lengths_and_batch_partitioning(kind: str) -> None:
    """Check algebraic and batch-boundary properties on complete outputs."""
    values = _deterministic_corpus(kind)
    before = values.copy()
    normalized = biov.normalize_sequences(values, kind=kind)
    reversed_values = biov.reverse_complements(values, kind=kind)

    assert biov.reverse_complements(reversed_values, kind=kind) == normalized
    assert biov.normalize_sequences(normalized, kind=kind) == normalized
    assert [None if value is None else len(value) for value in reversed_values] == [
        None if value is None else len(value) for value in values
    ]
    split = 19
    for operation in OPERATIONS:
        function = getattr(biov, operation)
        assert function(values, kind=kind) == (
            function(values[:split], kind=kind) + function(values[split:], kind=kind)
        )
    assert values == before


