def test_native_operations_do_not_call_biopython_reverse_complement(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Keep the migrated computation out of the old Python sequence backend."""

    def forbidden_reference_call(*args: object, **kwargs: object) -> None:
        pytest.fail("Native sequence computation called the Biopython reference")

    monkeypatch.setattr(ReferenceSeq, "reverse_complement", forbidden_reference_call)
    monkeypatch.setattr(
        ReferenceSeq, "reverse_complement_rna", forbidden_reference_call
    )
    assert biov.normalize_sequences(["aCgTryn", None, ""], kind="dna") == [
        "ACGTRYN",
        None,
        "",
    ]
    assert biov.reverse_complements(["aCgTryn", None, ""], kind="dna") == [
        "NRYACGT",
        None,
        "",
    ]
    assert biov.reverse_complements(["aCgUryn", None, ""], kind="rna") == [
        "NRYACGU",
        None,
        "",
    ]


@pytest.mark.parametrize(
    ("operation", "kind", "alphabet"),
    [
        ("normalize_sequences", "dna", DNA_ALPHABET),
        ("normalize_sequences", "rna", RNA_ALPHABET),
        ("normalize_sequences", "protein", PROTEIN_ALPHABET),
        ("reverse_complements", "dna", DNA_ALPHABET),
        ("reverse_complements", "rna", RNA_ALPHABET),
    ],
)
def test_ascii_acceptance_is_exact(operation: str, kind: str, alphabet: str) -> None:
    """Check every ASCII code point against the independently declared alphabet."""
    function = getattr(biov, operation)
    accepted = set(alphabet + alphabet.lower())
    for code_point in range(128):
        symbol = chr(code_point)
        if symbol in accepted:
            expected = symbol.upper()
            if operation == "reverse_complements":
                expected = _set_oracle(symbol, kind)
            assert function([symbol], kind=kind) == [expected], repr(symbol)
        else:
            with pytest.raises(biov.SequenceValidationError):
                function([symbol], kind=kind)


